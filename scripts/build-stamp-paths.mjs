// Converts the stamp lettering to outlined SVG paths so the stamp renders identically
// everywhere (including html-to-image export) without depending on web fonts.
// Run: node scripts/build-stamp-paths.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const load = (p) => {
  const b = readFileSync(p);
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
};
const ring = load('node_modules/@fontsource/josefin-sans/files/josefin-sans-latin-400-normal.woff');
const serif = load(
  'node_modules/@fontsource/cormorant-garamond/files/cormorant-garamond-latin-600-normal.woff',
);

const f = (n) => Number(n.toFixed(2));

// Circular text: centred on the top, clockwise, glyph tops pointing outward.
const CX = 100,
  CY = 100,
  R = 58.5,
  SIZE = 11.6,
  SPAN_DEG = 246;
const text = 'GOD HAS JOINED THEM TOGETHER';
const chars = [...text];
const adv = chars.map((c) => (ring.charToGlyph(c).advanceWidth / ring.unitsPerEm) * SIZE);
const arcLen = (SPAN_DEG * Math.PI * R) / 180;
const tracking = (arcLen - adv.reduce((a, b) => a + b, 0)) / (chars.length - 1);
let cursor = 0;
const ringGlyphs = [];
chars.forEach((c, i) => {
  const a = adv[i] ?? 0;
  if (c !== ' ') {
    const theta = -SPAN_DEG / 2 + ((cursor + a / 2) / arcLen) * SPAN_DEG;
    const rad = (theta * Math.PI) / 180;
    const x = CX + R * Math.sin(rad);
    const y = CY - R * Math.cos(rad);
    const d = ring.getPath(c, -a / 2, 0, SIZE).toPathData(2);
    ringGlyphs.push({ d, transform: `translate(${f(x)} ${f(y)}) rotate(${f(theta)})` });
  }
  cursor += a + tracking;
});

// "MARK 10:9", centred, with tracking.
const REF = 'MARK 10:9',
  RS = 10.8,
  RT = 1.3,
  RY = 154;
const radv = [...REF].map((c) => (serif.charToGlyph(c).advanceWidth / serif.unitsPerEm) * RS);
const total = radv.reduce((a, b) => a + b, 0) + RT * (REF.length - 1);
let rx = CX - total / 2;
const refPaths = [];
[...REF].forEach((c, i) => {
  if (c !== ' ') refPaths.push(serif.getPath(c, rx, RY, RS).toPathData(2));
  rx += (radv[i] ?? 0) + RT;
});

const out = `// GENERATED by scripts/build-stamp-paths.mjs, do not edit by hand.
export const RING_GLYPHS: ReadonlyArray<{ d: string; transform: string }> = ${JSON.stringify(ringGlyphs)};
export const REFERENCE_PATH = ${JSON.stringify(refPaths.join(' '))};
`;
writeFileSync('src/letter/stampPaths.ts', out);
console.log(`ring glyphs: ${ringGlyphs.length}, tracking ${tracking.toFixed(2)}`);
