// Builds supabase/seed.private.sql (gitignored) from the private design fixture, after checking
// it against the same zod schema the app uses. Run: npm run seed:build
import { existsSync, writeFileSync } from 'node:fs';
import { letterContentSchema } from '../src/lib/letterTypes';

const FIXTURE = 'src/dev-fixture/fixture.ts';
if (!existsSync(FIXTURE)) {
  console.error(
    `Missing ${FIXTURE}. It is gitignored, so it only exists on the machine that has it.`,
  );
  process.exit(1);
}

// A variable path keeps the type-check working on machines without the private fixture.
const fixturePath = '../src/dev-fixture/fixture';
const { fixture } = (await import(fixturePath)) as {
  fixture: { content: unknown; fontId: string };
};

const parsed = letterContentSchema.safeParse(fixture.content);
if (!parsed.success) {
  console.error('The letter content does not match the schema:');
  console.error(JSON.stringify(parsed.error.issues, null, 2));
  process.exit(1);
}

// Every non-ASCII character becomes a \uXXXX escape. The file is then plain ASCII, so copying it
// through a clipboard, terminal or editor with the wrong encoding cannot corrupt it (this once
// turned an em dash into mojibake). Postgres decodes the escapes, surrogate pairs included.
const json = JSON.stringify(parsed.data, null, 2).replace(
  /[\u0080-\uffff]/g,
  (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'),
);
if (json.includes('$content$')) throw new Error('Content contains the SQL quote tag');

const sql = `-- PRIVATE: generated by scripts/build-seed.ts. Never commit this file.
-- Run once against the Supabase database (SQL editor, or: psql "$DATABASE_URL" -f supabase/seed.private.sql).
-- Safe to re-run: it replaces the shared letter but never touches bridesmaids.

insert into public.letter_template (id, content, default_font)
values (1, $content$${json}$content$::jsonb, '${fixture.fontId}')
on conflict (id) do update
  set content = excluded.content,
      default_font = excluded.default_font;

-- Re-assert the WhatsApp message default (ASCII escapes: emoji and ellipsis) in case an earlier
-- copy of it was mangled in transit.
update public.letter_template
  set whatsapp_message_template =
    E'Hey {name} \\U0001F48C I''ve got something special for you\\u2026\\n\\nOpen it here: {link}\\nYour secret PIN: {pin}'
  where id = 1;
alter table public.letter_template
  alter column whatsapp_message_template set default
    E'Hey {name} \\U0001F48C I''ve got something special for you\\u2026\\n\\nOpen it here: {link}\\nYour secret PIN: {pin}';
`;

writeFileSync('supabase/seed.private.sql', sql);
console.log(`Wrote supabase/seed.private.sql (${parsed.data.chapters.length} chapters).`);
